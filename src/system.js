    function buildFromCoords(coords){
      clearSystem();
      coordsData = coords;
      for(let i=0;i<coords.length;i++){
        const c = coords[i];
        const p = {
          pos: { x:c.x, y:c.y, z:c.z },
          vel: { x:(Math.random()-0.5)*0.2, y:(Math.random()-0.5)*0.2, z:(Math.random()-0.5)*0.2 },
          force: { x:0, y:0, z:0 },
          mass: 1.0,
          charge: residueCharge[c.resname] || 0,
          resname: c.resname || 'UNK'
        };
        particles.push(p);
      }
      for(let i=0;i<particles.length-1;i++) bonds.push([i,i+1]);
      createMeshes();
      centerView();

      // Build structure info summary
      const info = buildStructureInfo(coords);
      setStructureInfo(info);
    }

    function buildStructureInfo(coords) {
      const helices = new Set();
      const sheets = new Set();
      const loops = new Set();
      const chains = new Set();
      const residues = new Set();

      for (const c of coords) {
        chains.add(c.chain);
        residues.add(c.resname);
        if (c.ss === 'helix' && c.helixIndex > 0) helices.add(c.helixIndex);
        if (c.ss === 'sheet' && c.sheetIndex > 0) sheets.add(c.sheetIndex);
        if (c.ss === 'loop' && c.loopIndex > 0) loops.add(c.loopIndex);
      }

      // Build segment list for legend
      const segments = [];
      let segStart = 0;
      while (segStart < coords.length) {
        const ss = coords[segStart].ss || 'loop';
        let segEnd = segStart;
        while (segEnd < coords.length - 1 && (coords[segEnd + 1].ss || 'loop') === ss) {
          segEnd++;
        }
        const color = getSSColor(coords[segStart]);
        const label = ss === 'helix' ? `Helix ${coords[segStart].helixIndex}`
                    : ss === 'sheet' ? `Sheet ${coords[segStart].sheetIndex}`
                    : `Loop ${coords[segStart].loopIndex}`;
        segments.push({
          type: ss,
          label,
          color: '#' + color.toString(16).padStart(6, '0'),
          startRes: coords[segStart].resSeq,
          endRes: coords[segEnd].resSeq,
          count: segEnd - segStart + 1
        });
        segStart = segEnd + 1;
      }

      return {
        totalResidues: coords.length,
        chains: [...chains],
        uniqueResidues: [...residues],
        helixCount: helices.size,
        sheetCount: sheets.size,
        loopCount: loops.size,
        segments
      };
    }

    // Add ligand atoms to the scene
    function buildLigand(ligandAtoms) {
      ligandGroup.clear();
      if (!ligandAtoms || ligandAtoms.length === 0) {
        ligandAtomsData = [];
        setLigandInfo(null);
        return;
      }

      ligandAtomsData = ligandAtoms;

      // Collect ligand info for UI
      const resnames = [...new Set(ligandAtoms.map(a => a.resname))];
      const elements = [...new Set(ligandAtoms.map(a => (a.element || 'C').toUpperCase()))];
      setLigandInfo({
        name: resnames.join(', '),
        atomCount: ligandAtoms.length,
        elements: elements
      });

      // --- Atom spheres: larger CPK-style, bright emissive glow ---
      const sphereGeom = new THREE.SphereGeometry(0.8, 20, 16);
      const glowGeom   = new THREE.SphereGeometry(1.05, 14, 12);

      for (const atom of ligandAtoms) {
        const color = getElementColor(atom.element);

        const mat = new THREE.MeshStandardMaterial({
          color,
          metalness: 0.1,
          roughness: 0.25,
          emissive: color,
          emissiveIntensity: 0.65
        });
        const mesh = new THREE.Mesh(sphereGeom, mat);
        mesh.position.set(atom.x, atom.y, atom.z);
        ligandGroup.add(mesh);

        // Outer glow halo
        const glowMat = new THREE.MeshBasicMaterial({
          color,
          transparent: true,
          opacity: 0.28,
          depthWrite: false,
          side: THREE.BackSide
        });
        const glowMesh = new THREE.Mesh(glowGeom, glowMat);
        glowMesh.position.set(atom.x, atom.y, atom.z);
        ligandGroup.add(glowMesh);
      }

      // --- Bonds: thicker cylinders, wider threshold for C-S / C-Cl / C-N etc. ---
      const bondGeom = new THREE.CylinderGeometry(0.18, 0.18, 1, 10);
      for (let i = 0; i < ligandAtoms.length; i++) {
        for (let j = i + 1; j < ligandAtoms.length; j++) {
          const dx = ligandAtoms[i].x - ligandAtoms[j].x;
          const dy = ligandAtoms[i].y - ligandAtoms[j].y;
          const dz = ligandAtoms[i].z - ligandAtoms[j].z;
          const dist = Math.sqrt(dx*dx + dy*dy + dz*dz);
          if (dist < 2.1) {  // wider threshold catches C-S, C-Cl, C-N, C-O bonds
            const colorA = getElementColor(ligandAtoms[i].element);
            const colorB = getElementColor(ligandAtoms[j].element);
            const va  = new THREE.Vector3(ligandAtoms[i].x, ligandAtoms[i].y, ligandAtoms[i].z);
            const vb  = new THREE.Vector3(ligandAtoms[j].x, ligandAtoms[j].y, ligandAtoms[j].z);
            const mid = new THREE.Vector3().addVectors(va, vb).multiplyScalar(0.5);
            const diff = new THREE.Vector3().subVectors(vb, va);
            const len  = diff.length();
            const quat = new THREE.Quaternion().setFromUnitVectors(
              new THREE.Vector3(0,1,0), diff.clone().normalize()
            );

            const mkHalf = (color, fromPt, toPt) => {
              const m = new THREE.MeshStandardMaterial({
                color, metalness: 0.05, roughness: 0.3,
                emissive: color, emissiveIntensity: 0.45
              });
              const h = new THREE.Mesh(bondGeom, m);
              const center = new THREE.Vector3().addVectors(fromPt, toPt).multiplyScalar(0.5);
              h.position.copy(center);
              h.quaternion.copy(quat);
              h.scale.set(1, len * 0.5, 1);
              return h;
            };

            ligandGroup.add(mkHalf(colorA, va, mid));
            ligandGroup.add(mkHalf(colorB, mid, vb));
          }
        }
      }

      // --- 3D bounding wireframe sphere (visible from all angles) ---
      if (ligandAtoms.length > 1) {
        const center = new THREE.Vector3();
        ligandAtoms.forEach(a => center.add(new THREE.Vector3(a.x, a.y, a.z)));
        center.divideScalar(ligandAtoms.length);

        let maxR = 0;
        ligandAtoms.forEach(a => {
          const d = center.distanceTo(new THREE.Vector3(a.x, a.y, a.z));
          if (d > maxR) maxR = d;
        });
        const boundR = maxR + 1.5;

        // Wireframe sphere cage
        const cageGeom = new THREE.IcosahedronGeometry(boundR, 1);
        const cageMat  = new THREE.MeshBasicMaterial({
          color: 0x00ff99,
          wireframe: true,
          transparent: true,
          opacity: 0.25
        });
        const cage = new THREE.Mesh(cageGeom, cageMat);
        cage.position.copy(center);
        ligandGroup.add(cage);

        // Solid ghost surface inside the cage
        const surfGeom = new THREE.SphereGeometry(boundR, 24, 18);
        const surfMat  = new THREE.MeshBasicMaterial({
          color: 0x00ff88,
          transparent: true,
          opacity: 0.06,
          depthWrite: false,
          side: THREE.FrontSide
        });
        const surf = new THREE.Mesh(surfGeom, surfMat);
        surf.position.copy(center);
        ligandGroup.add(surf);
      }

      ligandGroup.visible = true;
    }

