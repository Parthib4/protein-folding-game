// ---- physics helpers (vector ops on plain objects) ----
const MIN_DIST = 1e-3;
const residueCharge = { ARG:1, LYS:1, ASP:-1, GLU:-1 };
function v3(x=0,y=0,z=0){ return {x,y,z}; }
function vadd(a,b){ return {x:a.x+b.x,y:a.y+b.y,z:a.z+b.z}; }
function vsub(a,b){ return {x:a.x-b.x,y:a.y-b.y,z:a.z-b.z}; }
function vmul(a,s){ return {x:a.x*s,y:a.y*s,z:a.z*s}; }
function vdot(a,b){ return a.x*b.x + a.y*b.y + a.z*b.z; }
function vlen(a){ return Math.sqrt(Math.max(0, vdot(a,a))); }
function vzero(a){ a.x=0;a.y=0;a.z=0; return a; }
function clampR(r){ return (r < MIN_DIST) ? MIN_DIST : r; }
function randn_bm(){ let u=0,v=0; while(u===0) u=Math.random(); while(v===0) v=Math.random(); return Math.sqrt(-2*Math.log(u))*Math.cos(2*Math.PI*v); }

