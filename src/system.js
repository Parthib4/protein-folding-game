    function getIntersects(clientX, clientY){
      const rect = renderer.domElement.getBoundingClientRect();
      pointer.x = ((clientX - rect.left) / rect.width) * 2 - 1;
      pointer.y = - ((clientY - rect.top) / rect.height) * 2 + 1;
      ray.setFromCamera(pointer, camera);
      return ray.intersectObjects(beadGroup.children, true);
    }

    function onPointerDown(e){
      mouseDown = true;
      const hits = getIntersects(e.clientX, e.clientY);
      if(hits.length>0){
        const hit = hits[0];
        const mesh = hit.object;
        const idx = mesh.userData.index;
        const worldPos = hit.point;
        const p = particles[idx];
        const offset = new THREE.Vector3().subVectors(new THREE.Vector3(p.pos.x,p.pos.y,p.pos.z), worldPos);
        dragging = { index: idx, offset };
        p.vel = { x:0, y:0, z:0 };
      }
    }
    function onPointerMove(e){
      // Hover info
      const hits = getIntersects(e.clientX, e.clientY);
      if (hits.length > 0 && !mouseDown) {
        const mesh = hits[0].object;
        const ud = mesh.userData;
        setHoveredResidue({
          resname: ud.resname,
          resSeq: ud.resSeq,
          chain: ud.chain,
          ss: ud.ss,
          loopIndex: ud.loopIndex
        });
      } else if (!mouseDown) {
        setHoveredResidue(null);
      }

      if(!mouseDown || !dragging) return;
      const hits2 = getIntersects(e.clientX, e.clientY);
      const planePoint = ray.ray.origin.clone().add(ray.ray.direction.clone().multiplyScalar(10));
      const worldPos = hits2.length>0 ? hits2[0].point.clone() : planePoint;
      const newPos = worldPos.add(dragging.offset);
      const p = particles[dragging.index];
      p.pos.x = newPos.x; p.pos.y = newPos.y; p.pos.z = newPos.z;
      p.vel = { x:0, y:0, z:0 };
      syncMeshes();
    }
    function onPointerUp(e){
      mouseDown = false;
      dragging = null;
    }

