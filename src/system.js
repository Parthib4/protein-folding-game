    // ---- Protein-bound residue detection ----
    function computeBoundResidues(distanceThreshold) {
      if (particles.length === 0 || ligandAtomsData.length === 0) {
        setBoundResidues([]);
        setBoundResidueInfo([]);
        return;
      }
      
      const bound = new Set();
      const boundInfo = [];
      const dist2 = distanceThreshold * distanceThreshold;
      
      // For each protein residue (particle), check if any ligand atom is within distance threshold
      for (let i = 0; i < particles.length; i++) {
        const p = particles[i];
        let isBound = false;
        
        for (const ligAtom of ligandAtomsData) {
          const dx = p.pos.x - ligAtom.x;
          const dy = p.pos.y - ligAtom.y;
          const dz = p.pos.z - ligAtom.z;
          const d2 = dx*dx + dy*dy + dz*dz;
          
          if (d2 <= dist2) {
            isBound = true;
            break;
          }
        }
        
        if (isBound) {
          bound.add(i);
          const coord = coordsData[i] || {};
          boundInfo.push({
            index: i,
            resname: coord.resname || 'UNK',
            resSeq: coord.resSeq || i + 1,
            chain: coord.chain || 'A'
          });
        }
      }
      
      setBoundResidues(Array.from(bound));
      setBoundResidueInfo(boundInfo);
    }

