function getElementColor(element) {
  const el = (element || 'C').toUpperCase();
  return ELEMENT_COLORS[el] || ELEMENT_COLORS.DEFAULT;
}

// Get color for a residue based on its secondary structure
function getSSColor(coord) {
  if (coord.ss === 'helix') {
    return HELIX_COLORS[(coord.helixIndex - 1) % HELIX_COLORS.length];
  }
  if (coord.ss === 'sheet') {
    return SHEET_COLORS[(coord.sheetIndex - 1) % SHEET_COLORS.length];
  }
  // loop - each segment gets a unique color
  return LOOP_COLORS[(coord.loopIndex - 1) % LOOP_COLORS.length];
}

