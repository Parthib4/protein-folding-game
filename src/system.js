// ---- AutoDock atom type mapping ----
function getAutodockType(element, atomName) {
  const el = (element || 'C').toUpperCase().replace(/[0-9]/g, '').trim();
  switch (el) {
    case 'C':  return 'C';
    case 'N':  return 'NA';
    case 'O':  return 'OA';
    case 'S':  return 'SA';
    case 'H':  return 'HD';
    case 'P':  return 'P';
    case 'F':  return 'F';
    case 'CL': return 'Cl';
    case 'BR': return 'Br';
    case 'I':  return 'I';
    case 'FE': return 'Fe';
    case 'ZN': return 'Zn';
    case 'MG': return 'Mg';
    case 'CA': return 'Ca';
    case 'MN': return 'Mn';
    case 'NA': return 'Na';
    case 'K':  return 'K';
    default:   return el.length <= 2 ? el : el.substring(0, 2);
  }
}

// Generate protein PDBQT from raw PDB text (all-atom ATOM records)
function generateProteinPDBQT(pdbText) {
  const lines = pdbText.split('\n');
  const out = [];
  out.push('REMARK  PDBQT receptor - generated by Protein Structure Viewer');
  let serial = 1;
  for (const line of lines) {
    const recType = line.substring(0, 6).trim();
    if (recType !== 'ATOM') continue;
    const resname = line.substring(17, 20).trim();
    if (!resname) continue;
    const atomName = line.substring(12, 16).trim();
    const altLoc   = line.substring(16, 17).trim();
    if (altLoc && altLoc !== 'A') continue; // skip alternate conformations
    const chain  = line.substring(21, 22) || 'A';
    const resSeq = line.substring(22, 26);
    const x = parseFloat(line.substring(30, 38));
    const y = parseFloat(line.substring(38, 46));
    const z = parseFloat(line.substring(46, 54));
    if (isNaN(x) || isNaN(y) || isNaN(z)) continue;
    const rawEl = line.substring(76, 78).trim();
    const element = rawEl || atomName.replace(/[0-9]/g, '').charAt(0);
    const adType = getAutodockType(element, atomName);
    const charge = '0.000';
    const sn   = serial.toString().padStart(5);
    const aStr = (' ' + atomName).padEnd(4).substring(0, 4);
    const xStr = x.toFixed(3).padStart(8);
    const yStr = y.toFixed(3).padStart(8);
    const zStr = z.toFixed(3).padStart(8);
    out.push(`ATOM  ${sn} ${aStr} ${resname.padEnd(3)} ${chain}${resSeq}    ${xStr}${yStr}${zStr}  1.00  0.00    ${charge.padStart(6)} ${adType}`);
    serial++;
  }
  out.push('END');
  return out.join('\n');
}

// Generate ligand PDBQT from parsed ligand atoms array
function generateLigandPDBQT(ligandAtoms) {
  if (!ligandAtoms || ligandAtoms.length === 0) return '';
  const out = [];
  out.push('REMARK  PDBQT ligand - generated by Protein Structure Viewer');
  out.push('ROOT');
  ligandAtoms.forEach((atom, i) => {
    const serial  = (i + 1).toString().padStart(5);
    const aName   = (atom.atomName || atom.element || 'C').padEnd(4).substring(0, 4);
    const resname = (atom.resname || 'LIG').padEnd(3).substring(0, 3);
    const chain   = (atom.chain || 'Z').charAt(0);
    const resSeq  = ((atom.resSeq || 1) + '').padStart(4);
    const xStr    = atom.x.toFixed(3).padStart(8);
    const yStr    = atom.y.toFixed(3).padStart(8);
    const zStr    = atom.z.toFixed(3).padStart(8);
    const element = (atom.element || 'C').toUpperCase();
    const adType  = getAutodockType(element, atom.atomName);
    const charge  = '0.000';
    out.push(`HETATM${serial}  ${aName}${resname} ${chain}${resSeq}    ${xStr}${yStr}${zStr}  1.00  0.00    ${charge.padStart(6)} ${adType}`);
  });
  out.push('ENDROOT');
  out.push('TORSDOF 0');
  return out.join('\n');
}

