    function generateRandomChain(n){
      const coords = [];
      // Assign random secondary structure segments for demo
      let currentSS = 'loop';
      let loopIdx = 1, helixIdx = 0, sheetIdx = 0;
      let segLen = 0;
      const maxSegLen = () => currentSS === 'helix' ? 12 : currentSS === 'sheet' ? 6 : 5;

      for(let i=0;i<n;i++){
        segLen++;
        if (segLen > maxSegLen() || i === 0) {
          const r = Math.random();
          if (r < 0.35) { currentSS = 'helix'; helixIdx++; }
          else if (r < 0.55) { currentSS = 'sheet'; sheetIdx++; }
          else { currentSS = 'loop'; loopIdx++; }
          segLen = 1;
        }
        coords.push({
          x: i*params.r0*1.05 + (Math.random()-0.5)*0.2,
          y: (Math.random()-0.5)*0.2,
          z: (Math.random()-0.5)*0.2,
          resname: randomResidue(),
          chain: 'A',
          resSeq: i+1,
          ss: currentSS,
          loopIndex: currentSS === 'loop' ? loopIdx : -1,
          helixIndex: currentSS === 'helix' ? helixIdx : -1,
          sheetIndex: currentSS === 'sheet' ? sheetIdx : -1
        });
      }
      buildFromCoords(coords);
    }
    function randomResidue(){
      const keys = Object.keys(residueCharge);
      const others = ['ALA','GLY','SER','PHE','TYR','TRP','ASN'];
      const pool = keys.concat(others);
      return pool[Math.floor(Math.random()*pool.length)];
    }

    function centerView(){
      if(particles.length===0) return;
      let cx=0, cy=0, cz=0;
      for(let p of particles){ cx+=p.pos.x; cy+=p.pos.y; cz+=p.pos.z; }
      cx/=particles.length; cy/=particles.length; cz/=particles.length;
      controls.target.set(cx,cy,cz);
      const spread = Math.max(10, Math.sqrt(particles.length) * 3);
      camera.position.set(cx + spread * 0.5, cy + spread * 0.3, cz + spread);
      controls.update();
    }

